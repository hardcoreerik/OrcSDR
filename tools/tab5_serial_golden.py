#!/usr/bin/env python3
"""Replay the unauthenticated serial golden file against a Tab5 and compare every reply exactly.

  python tools/tab5_serial_golden.py --self-check          no hardware: tests the comparison logic
  python tools/tab5_serial_golden.py --port COM17          talks to the device on that port

The inputs come from tests/data/serial_golden_unauthenticated.tsv (generated by
tools/serial_command_routes.py). Every one of them is refused by the first
statement of its route while the session is not authenticated, so a run changes
nothing on the device. To make sure of that the tool sends one probe first,
`RTL_MEM HOG 0`, which is harmless in either state (0 is below the accepted
range): if the reply is not the auth_required refusal the session is
authenticated and the tool stops before sending anything else.

The port is opened without asserting DTR or RTS so the board is not reset.
Needs pyserial for a device run. Exit status 0 only when every reply matched.
"""
from __future__ import annotations

import argparse
import pathlib
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "tests/data/serial_golden_unauthenticated.tsv"
PROBE = ("RTL_MEM HOG 0", "RTL_MEM_ERROR auth_required")
CRASH_MARKERS = ("ESP-ROM:", "Guru Meditation", "assert failed", "Rebooting...")


def load_golden(path: pathlib.Path = GOLDEN) -> list[tuple[str, str]]:
    rows = []
    for raw in path.read_bytes().decode("utf-8").replace("\r\n", "\n").split("\n"):
        if not raw or raw.startswith("#") or raw == "input\texpected_reply":
            continue
        line, _, reply = raw.partition("\t")
        if not line or not reply:
            raise ValueError(f"malformed golden row: {raw!r}")
        rows.append((line, reply))
    return rows


def reply_family(expected: str) -> str:
    """The tag that identifies a reply line as the answer to this command, e.g. 'RTL_MEM_ERROR'."""
    return expected.split(" ", 1)[0]


def exchange(port, line: str, expected: str, timeout: float) -> tuple[bool, str]:
    """Send one line; return (matched, what was seen). Unrelated log lines are skipped; a line with the reply's
    own tag must equal the expected reply exactly."""
    port.write((line + "\n").encode("ascii"))
    family = reply_family(expected)
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        raw = port.readline()
        if not raw:
            continue
        seen = raw.decode("utf-8", "replace").rstrip("\r\n")
        if any(marker in seen for marker in CRASH_MARKERS):
            raise RuntimeError(f"device restarted or crashed after {line!r}: {seen}")
        if seen.split(" ", 1)[0] == family:
            return seen == expected, seen
    return False, "<no reply>"


def run(port, rows: list[tuple[str, str]], timeout: float) -> int:
    matched, seen = exchange(port, PROBE[0], PROBE[1], timeout)
    if not matched:
        print(f"STOP: probe {PROBE[0]!r} answered {seen!r}, not the auth_required refusal. The session looks "
              f"authenticated (or the port is wrong); nothing else was sent.")
        return 2
    failures = 0
    for line, expected in rows:
        matched, seen = exchange(port, line, expected, timeout)
        if not matched:
            failures += 1
            print(f"MISMATCH {line!r}\n  expected: {expected}\n  seen:     {seen}")
    print(f"{'PASS' if failures == 0 else 'FAIL'}: {len(rows) - failures} of {len(rows)} replies matched exactly")
    return 0 if failures == 0 else 1


def self_check() -> None:
    class Fake:
        def __init__(self, answers):
            self.answers = answers
            self.queue = []
            self.sent = []
        def write(self, data):
            line = data.decode("ascii").rstrip("\n")
            self.sent.append(line)
            self.queue = list(self.answers.get(line, []))
        def readline(self):
            return self.queue.pop(0) if self.queue else b""

    rows = [("RTL_GAIN 0", "RTL_GAIN_ERROR auth_required"), ("RTL_RESET", "RTL_RESET_ERROR auth_required")]
    good = {
        "RTL_MEM HOG 0": [b"RTL_DSP noise line\r\n", b"RTL_MEM_ERROR auth_required\r\n"],
        "RTL_GAIN 0": [b"RTL_GAIN_ERROR auth_required\n"],
        "RTL_RESET": [b"RTL_RESET_ERROR auth_required\r\n"],
    }
    assert run(Fake(good), rows, timeout=0.05) == 0
    # A changed reply text is a failure, not a pass.
    changed = dict(good, **{"RTL_GAIN 0": [b"RTL_GAIN_ERROR authentication_required\n"]})
    assert run(Fake(changed), rows, timeout=0.05) == 1
    # Silence is a failure.
    assert run(Fake(dict(good, **{"RTL_RESET": []})), rows, timeout=0.05) == 1
    # An authenticated session: the probe is answered differently and nothing else is sent.
    authenticated = Fake({"RTL_MEM HOG 0": [b"RTL_MEM_ERROR use=RTL_MEM HOG <64..32768 KiB to leave free>\n"]})
    assert run(authenticated, rows, timeout=0.05) == 2 and authenticated.sent == ["RTL_MEM HOG 0"]
    # A crash is reported, never counted as a mismatch.
    try:
        run(Fake(dict(good, **{"RTL_GAIN 0": [b"Guru Meditation Error: Core 0\n"]})), rows, timeout=0.05)
    except RuntimeError:
        pass
    else:
        raise AssertionError("a crash must stop the run")
    golden = load_golden()
    assert golden and all(reply for _, reply in golden)
    assert PROBE in golden, "the probe must itself be a golden row"
    print(f"PASS self-check: exact match, changed text, silence, authenticated stop, crash; "
          f"{len(golden)} golden rows load")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--self-check", action="store_true")
    parser.add_argument("--port", help="serial port of the Tab5, e.g. COM17; never auto-detected")
    parser.add_argument("--baud", type=int, default=115200)
    parser.add_argument("--timeout", type=float, default=3.0, help="seconds to wait for each reply")
    args = parser.parse_args()
    if args.self_check:
        self_check()
        return 0
    if not args.port:
        parser.error("give --port (the tool never picks a port itself) or --self-check")
    import serial  # pyserial; imported here so --self-check needs nothing installed

    port = serial.Serial()
    port.port, port.baudrate, port.timeout = args.port, args.baud, 0.2
    port.dtr = False
    port.rts = False
    port.open()
    try:
        port.reset_input_buffer()
        return run(port, load_golden(), args.timeout)
    finally:
        port.close()


if __name__ == "__main__":
    sys.exit(main())
