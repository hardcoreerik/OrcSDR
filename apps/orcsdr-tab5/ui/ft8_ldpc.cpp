codec::CodewordBits encode(const codec::MessageBits& message) {
  codec::CodewordBits codeword{};
  std::copy(message.begin(), message.end(), codeword.begin());
  for (std::size_t row = 0; row < kCheckCount; ++row) {
    uint8_t parity = 0;
    for (std::size_t column = 0; column < codec::kMessageBits; ++column)
      parity ^= static_cast<uint8_t>((message[column] & 1u) & generator_bit(row, column));
    codeword[codec::kMessageBits + row] = parity;
  }
  return codeword;
}

Syndrome syndrome(const codec::CodewordBits& codeword) {
  Syndrome result{};
  for (std::size_t column = 0; column < codeword.size(); ++column) {
    if ((codeword[column] & 1u) == 0) continue;
    for (uint8_t check : kColumnChecks[column]) result[check] ^= 1u;
  }
  return result;
}

std::size_t syndrome_weight(const Syndrome& value) {
  std::size_t weight = 0;
  for (uint8_t bit : value) weight += bit & 1u;
  return weight;
}

bool valid(const codec::CodewordBits& codeword) {
  return syndrome_weight(syndrome(codeword)) == 0;
}

bool self_check() {
  codec::MessageBits zero{};
  if (!valid(encode(zero))) return false;
  codec::MessageBits pattern{};
  for (std::size_t i = 0; i < pattern.size(); ++i)
    pattern[i] = static_cast<uint8_t>(((i * 17u + 5u) ^ (i >> 1u)) & 1u);
  codec::CodewordBits codeword = encode(pattern);
  if (!valid(codeword)) return false;
  codeword[0] ^= 1u;
  return syndrome_weight(syndrome(codeword)) == 3u;
}

